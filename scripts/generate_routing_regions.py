# -*- coding: utf-8 -*-
"""将共享地区 JSON 生成为同步加载的前端资源，运行时无需联网。"""
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def render_catalog(catalog):
    rows = [f'  {json.dumps(code)}: {json.dumps(value, ensure_ascii=False)},'
            for code, value in catalog.items()]
    return ('/* Generated by scripts/generate_routing_regions.py from routing_regions.json. */\n'
            'window.RoutingRegionCatalog = Object.freeze({\n' + '\n'.join(rows) + '\n});\n')


if __name__ == '__main__':
    catalog = json.loads((ROOT / 'ui/routing_regions.json').read_text(encoding='utf-8'))
    (ROOT / 'ui/routing_regions.js').write_text(render_catalog(catalog), encoding='utf-8')
