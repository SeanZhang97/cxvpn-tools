const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, '../ui/proxy.js'), 'utf8');
const start = source.indexOf('  function usesProxy(');
const end = source.indexOf('  function usesSubscriptionSelection(', start);
const context = vm.createContext({});
vm.runInContext(source.slice(start, end), context);
const usesProxy = context.usesProxy;
assert.equal(usesProxy({ default_outbound: 'physical' }), false);
assert.equal(usesProxy({ default_outbound: 'proxy:local' }), true);
assert.equal(usesProxy({ default_outbound: 'proxy' }), true);
const business = { default_outbound: 'physical', business_rules: [{ outbound: 'outbound:chat' }] };
assert.equal(usesProxy(business), true);
assert.equal(usesProxy({ ...business, traffic_mode: 'global' }), false);
assert.equal(usesProxy({ ...business, business_rules: [{ outbound: 'outbound:chat', enabled: false }] }), false);
assert.equal(usesProxy({ default_outbound: 'physical', rules: [{ outbound: 'outbound:git' }] }), true);
assert.equal(usesProxy({ default_outbound: 'vpn:公司' }), false);
assert.doesNotMatch(source, /runtimeUsesProxy|所有流量都走直连|系统流量仍将直连|proxy-default-outbound/);
assert.match(source, /!usesProxy\(\{ \.\.\.config, traffic_mode: targetMode \}\)/);
assert.match(source, /status\.configuration_pending[\s\S]*?usesProxy\(config\) \? '' : '当前配置未使用代理订阅。'/);
assert.match(source, /renderModeConsole\(config, status, running\)/);
console.log('proxy direct-mode compatibility: passed');
